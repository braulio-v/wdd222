const template = document.querySelector('#product-card');
const productList = document.querySelector('#product-list');

products.forEach((product) => {
    const clone = template.content.cloneNode(true);
    const [title, topics, description, opportunities, duration, exercises] = clone.querySelectorAll("h2, ul, p, p, p, p");

    title.textContent = `Title: ${product.title}`;
    topics.innerHTML = `<strong>Topic:</strong> ${product.topics.map((topic) => `<li>${topic}</li>`).join('')}`;
    description.innerHTML = `<strong>Description:</strong> ${product.description}`;
    opportunities.innerHTML = `<strong>Opportunities:</strong> ${product.opportunities}`;
    duration.innerHTML = `<strong>Duration:</strong> ${product.duration}`;
    exercises.innerHTML = product.exercises.map((exercise) => `<a href="${exercise.url}" target="_blank">${exercise.name}</a>`).join('<br>');

    productList.appendChild(clone);
});